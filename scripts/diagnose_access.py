"""Diagnóstico local somente leitura. Nunca inclui chave/hashes no relatório."""
from contextlib import closing
from pathlib import Path
import argparse
import getpass
import hashlib
import hmac
import json
import sqlite3
import sys

APPLICATION_ID=0x53414932


def inspect_database(path,key):
    path=Path(path).resolve()
    if not path.is_file():return {'match':'MISSING'}
    try:
        with closing(sqlite3.connect(path.as_uri()+'?mode=ro',uri=True,timeout=3)) as conn:
            conn.row_factory=sqlite3.Row
            conn.execute('PRAGMA query_only=ON')
            if conn.execute('PRAGMA application_id').fetchone()[0]!=APPLICATION_ID:
                return {'match':'OTHER_DATABASE'}
            row=conn.execute('SELECT recovery_salt,recovery_hash,iterations FROM admin_credentials WHERE id=1').fetchone()
            if row is None:return {'match':'NO_CREDENTIALS'}
            if not 1<=row['iterations']<=2000000:return {'match':'READ_ERROR'}
            matched='NO_MATCH'
            # Tokens generated by the application never contain whitespace.
            for label,candidate in [('EXACT',key),('OUTER_WHITESPACE',key.strip()),('INNER_WHITESPACE',''.join(key.split()))]:
                hashed=hashlib.pbkdf2_hmac('sha256',candidate.encode(),row['recovery_salt'],row['iterations'])
                if hmac.compare_digest(hashed,row['recovery_hash']):
                    matched=label;break
            events=conn.execute("SELECT count(*),max(occurred_at) FROM audit_events WHERE kind='security.recovered'").fetchone()
            return {'match':matched,'recoveries':events[0],'last_recovery':events[1]}
    except (sqlite3.Error,OSError,ValueError,TypeError):
        return {'match':'READ_ERROR'}


def diagnose(data_dir,key):
    root=Path(data_dir).resolve()
    active=inspect_database(root/'dados'/'salva_ai.sqlite3',key)
    report={'diagnostic_version':1,'active':active,'backups_checked':0,'backup_matches':0,'backup_read_errors':0}
    if active['match']!='NO_MATCH':return report
    try:
        backups=sorted((root/'backups').glob('*.sqlite3'),key=lambda p:p.stat().st_mtime,reverse=True)[:20]
        for path in backups:
            result=inspect_database(path,key)
            report['backups_checked']+=1
            if result['match'] in ('EXACT','OUTER_WHITESPACE','INNER_WHITESPACE'):report['backup_matches']+=1
            elif result['match']=='READ_ERROR':report['backup_read_errors']+=1
    except OSError:report['backup_scan_error']=True
    return report


def main(argv=None):
    parser=argparse.ArgumentParser(description='Diagnóstico local de chave, sem alterar credenciais ou dados.')
    parser.add_argument('--data-dir',type=Path,default=Path.home()/'SalvaAiHeadshopV2')
    args=parser.parse_args(argv)
    if not sys.stdin.isatty():
        print('Abra DIAGNOSTICAR_ACESSO.bat em um terminal local para informar a chave sem exibi-la.')
        return 1
    print('Feche o programa antes de continuar. Nenhuma informação será enviada pela internet.')
    print('Cole a chave e pressione Enter. A chave não aparece enquanto você cola/digita.')
    try:key=getpass.getpass('Chave de recuperação: ')
    except (EOFError,KeyboardInterrupt):return 1
    report=diagnose(args.data_dir,key)
    key=None
    body=json.dumps(report,ensure_ascii=False,indent=2)
    print('\nRELATÓRIO (não contém a chave, senha, PIN ou hashes):\n'+body)
    target=Path(__file__).resolve().parent/'RELATORIO_ACESSO.txt'
    try:
        target.write_text(body+'\n',encoding='utf-8')
        print('\nRelatório salvo em RELATORIO_ACESSO.txt, ao lado deste diagnóstico.')
    except OSError:print('\nNão foi possível salvar o relatório. Copie apenas o resultado acima.')
    print('Nenhuma credencial, produto, venda ou backup foi alterado.')
    return 0


if __name__=='__main__':raise SystemExit(main())
